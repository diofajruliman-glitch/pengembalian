-- Profile hanya dapat dibaca akun sendiri; role tidak dapat diubah melalui aplikasi.
drop policy if exists own_profile_read on public.profiles;
create policy own_profile_read on public.profiles for select to authenticated using (id = (select auth.uid()));

DO $$ declare tbl text; begin
 foreach tbl in array array['bottlenecks','action_plans','bank_recap','sdm_cases'] loop
  execute format('drop policy if exists scoped_read on public.%I',tbl);
  execute format('drop policy if exists scoped_insert on public.%I',tbl);
  execute format('drop policy if exists scoped_update on public.%I',tbl);
  execute format('create policy scoped_read on public.%I for select to authenticated using ((select public.current_app_role()) in (''admin'',''editor'',''viewer''))',tbl);
  execute format('create policy scoped_insert on public.%I for insert to authenticated with check ((select public.current_app_role()) in (''admin'',''editor''))',tbl);
  execute format('create policy scoped_update on public.%I for update to authenticated using ((select public.current_app_role()) in (''admin'',''editor'')) with check ((select public.current_app_role()) in (''admin'',''editor''))',tbl);
 end loop;
end $$;
drop policy if exists admin_audit_read on public.audit_events;
create policy admin_audit_read on public.audit_events for select to authenticated using ((select public.current_app_role())='admin');

