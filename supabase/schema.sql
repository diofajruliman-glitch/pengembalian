 gagal_terakhir integer check (gagal_terakhir >= 0),
 cutoff date,
 status text,
 bukti text,
 catatan text,
 updated_at timestamptz not null default now(),
 constraint bank_realization_not_over_obligation check (realisasi_netto is null or kewajiban_total is null or realisasi_netto <= kewajiban_total)
);
create table if not exists public.sdm_cases (
 id bigint generated by default as identity primary key,
 nip varchar(18) not null unique check (nip ~ '^[0-9]{18}$'),
 nama text not null,
 provinsi text,
 kab_kota text,
 bank text not null,
 kategori text,
 kewajiban_total numeric(18,0) not null default 0 check (kewajiban_total >= 0),
 realisasi_total numeric(18,0) not null default 0 check (realisasi_total >= 0 and realisasi_total <= kewajiban_total),
 sisa_kewajiban numeric(18,0) generated always as (kewajiban_total - realisasi_total) stored,
 tahap_terakhir text,
 jalur_penyelesaian text,
 pic text,
 deadline date,
 status text not null default 'Belum Ditindaklanjuti',
 bukti text,
 tanggal_pembayaran date,
 catatan text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint verified_payment_must_have_evidence check (status <> 'Lunas Terverifikasi' or (kewajiban_total > 0 and realisasi_total = kewajiban_total and nullif(btrim(bukti),'') is not null and tanggal_pembayaran is not null))
);
create index if not exists idx_cases_province on public.sdm_cases(provinsi);
