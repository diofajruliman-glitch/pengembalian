create table if not exists public.bank_recap (
 bank text primary key check (bank in ('Mandiri','BRI','BSI')),
 jumlah_sdm integer check (jumlah_sdm >= 0),
 kewajiban_total numeric(18,0) check (kewajiban_total >= 0),
