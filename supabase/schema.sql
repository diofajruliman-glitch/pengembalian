create table if not exists public.audit_events (
 id bigint generated by default as identity primary key,
 actor uuid,
 entity text not null,
 row_key text not null,
 action text not null,
 old_data jsonb,
 new_data jsonb,
 occurred_at timestamptz not null default now()
);

create or replace function public.touch_updated_at() returns trigger
 language plpgsql set search_path = public as $$
 begin new.updated_at := now(); return new; end $$;
create or replace function public.record_audit_event() returns trigger
 language plpgsql security definer set search_path = public as $$
 begin
 insert into public.audit_events(actor,entity,row_key,action,old_data,new_data)
 values(auth.uid(),TG_TABLE_NAME,case when TG_OP='DELETE' then coalesce(to_jsonb(old)->>'nip',to_jsonb(old)->>'no',to_jsonb(old)->>'bank') else coalesce(to_jsonb(new)->>'nip',to_jsonb(new)->>'no',to_jsonb(new)->>'bank') end,TG_OP,
 case when TG_OP='INSERT' then null else to_jsonb(old) end,
 case when TG_OP='DELETE' then null else to_jsonb(new) end);
 return coalesce(new,old);
 end $$;
revoke all on function public.record_audit_event() from public,anon,authenticated;

DO $$ declare tbl text; begin
 foreach tbl in array array['bottlenecks','action_plans','bank_recap','sdm_cases'] loop
  execute format('drop trigger if exists touch_modified on public.%I',tbl);
  execute format('create trigger touch_modified before update on public.%I for each row execute function public.touch_updated_at()',tbl);
  execute format('drop trigger if exists audit_modified on public.%I',tbl);
  execute format('create trigger audit_modified after insert or update or delete on public.%I for each row execute function public.record_audit_event()',tbl);
 end loop;
end $$;

